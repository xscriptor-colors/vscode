#!/usr/bin/env node
/**
 * generate-color-themes.mjs
 *
 * Regenera los color themes completos en una carpeta `dist/` SIN reemplazar los
 * originales. Completa todas las keys de color que VS Code documenta, derivando
 * los valores faltantes desde la paleta real de cada tema (background, foreground,
 * accent, colores semánticos red/green/yellow/blue/orange/purple, alphas).
 *
 * Uso:
 *   node labs/xscriptor-themes/scripts/generate-color-themes.mjs
 *   node labs/xscriptor-themes/scripts/generate-color-themes.mjs --dist dist/themes
 *   node labs/xscriptor-themes/scripts/generate-color-themes.mjs --dry-run
 *
 * La salida se escribe en `dist/` (por defecto `themes/xscriptor-themes/dist`).
 * Cada tema se genera partiendo del JSON actual, preservando el formato original
 * (tabs o espacios, CRLF o LF, orden de keys) y añadiendo SOLO las keys faltantes.
 */

