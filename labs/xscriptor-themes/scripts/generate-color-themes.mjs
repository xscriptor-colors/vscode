// ── Preservación del formato original ──
function detectFormat(origText) {
  const crlf = origText.includes("\r\n");
  const eol = crlf ? "\r\n" : "\n";
  const lines = origText.split(eol);
  const start = lines.findIndex((l) => l.includes('"colors": {'));
  const padMatch = lines[start + 1] ? lines[start + 1].match(/^(\s+)/) : null;
  const pad = padMatch ? padMatch[1] : "\t\t";
  return { eol, pad, start };
}

function rebuild(origText, mergedColors, data) {
  const { eol, pad, start } = detectFormat(origText);
  const lines = origText.split(eol);
  let depth = 0;
  let end = lines.length - 1;
  for (let i = start; i < lines.length; i++) {
    depth += (lines[i].match(/{/g) || []).length - (lines[i].match(/}/g) || []).length;
    if (depth === 0) { end = i; break; }
  }
  const keys = Object.keys(mergedColors);
  const block = keys.map((k, i) => {
    const comma = i < keys.length - 1 ? "," : "";
    return `${pad}"${k}": ${JSON.stringify(mergedColors[k])}${comma}`;
  });
  return lines.slice(0, start + 1).concat(block, [lines[end]], lines.slice(end + 1)).join(eol);
}

// ── Modo desde paleta (--from-palette) ──
// Toma un colors.md (o un JSON de paletas) con bloques {color0..15, background, foreground}
// y regenera los temas completos desde cero, sin partir de los temas existentes.
const PALETTE_PATH = flag("--palette", "themes/xscriptor-themes/colors.md");

function parsePaletteFile(p) {
  const text = fs.readFileSync(p, "utf8");
  const out = {};
  if (text.trimStart().startsWith("{")) {
    const obj = JSON.parse(text);
    for (const [name, pal] of Object.entries(obj)) {
      if (pal && pal.color0) out[name.toLowerCase()] = pal;
    }
    return out;
  }
  // colors.md: <h2 align="center">Name</h2> ... ```json {...}```
  const re = /<h2 align="center">([^<]+)<\/h2>[\s\S]*?```json\s*\n([\s\S]*?)```/g;
  let m;
  while ((m = re.exec(text))) {
    out[m[1].trim().toLowerCase()] = JSON.parse(m[2]);
  }
  return out;
}

