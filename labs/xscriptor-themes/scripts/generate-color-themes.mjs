function buildThemeFromSeed(seed, name) {
  // Aplica TODAS las reglas para completar el tema desde la semilla.
  const merged = {};
  for (const k of Object.keys(seed)) merged[k] = seed[k];
  const resolver = new Resolver(seed);
  for (const k of ALL_KEYS) {
    if (k in merged) continue;
    const rule = RULES[k];
    if (!rule) continue;
    const v = rule(resolver);
    if (v == null) continue;
    merged[k] = v;
  }
  return merged;
}

function emitTheme(name, merged) {
  // Escribe el tema como JSON con el formato estándar del repo (tabs + CRLF).
  const label = name.charAt(0).toUpperCase() + name.slice(1);
  const lines = ["{", `\t"name": ${JSON.stringify(label)},`, '\t"$schema": "vscode://schemas/color-theme",',
    `\t"type": ${JSON.stringify(merged["editor.background"] && isLight(merged["editor.background"]) ? "light" : "dark")},`,
    '\t"colors": {'];
  const keys = Object.keys(merged);
  for (let i = 0; i < keys.length; i++) {
    const comma = i < keys.length - 1 ? "," : "";
    lines.push(`\t\t${JSON.stringify(keys[i])}: ${JSON.stringify(merged[keys[i]])}${comma}`);
  }
  lines.push("\t}");
  lines.push("}");
  return lines.join("\r\n") + "\r\n";
}

function isLight(hex) {
  const [r, g, b] = hexToRgb(hex);
  return 0.2126 * r + 0.7152 * g + 0.0722 * b > 128;
}

// ── Generación ──
function main() {
  const srcAbs = path.resolve(process.cwd(), SRC_DIR);
  const distAbs = path.resolve(process.cwd(), DIST_DIR);

  if (FROM_PALETTE) {
    const palAbs = path.resolve(process.cwd(), PALETTE_PATH);
    if (!fs.existsSync(palAbs)) {
      console.error(`No existe la paleta: ${palAbs}`);
      process.exit(1);
    }
    const palettes = parsePaletteFile(palAbs);
    const names = Object.keys(palettes).sort();
    console.log(`Modo paleta: ${names.length} paletas → ${DIST_DIR}\n`);
    for (const name of names) {
      const merged = buildThemeFromSeed(seedFromPalette(palettes[name]), name);
      const outText = emitTheme(name, merged);
      if (!DRY_RUN) {
        fs.mkdirSync(distAbs, { recursive: true });
        fs.writeFileSync(path.join(distAbs, name + ".json"), outText, "utf8");
      }
      const missing = ALL_KEYS.filter((k) => !(k in merged));
      console.log(
        `${name.padEnd(14)} ${String(Object.keys(merged).length).padStart(4)} keys  [${missing.length === 0 ? "OK" : `faltan ${missing.length}`}]${DRY_RUN ? "  (dry-run)" : ""}`
      );
    }
    if (DRY_RUN) console.log("\n(dry-run: no se escribió nada)");
    else console.log(`\nListo. Resultados en: ${distAbs}`);
    return;
  }

  if (!fs.existsSync(srcAbs)) {
    console.error(`No existe: ${srcAbs}`);
    process.exit(1);
  }
  const files = fs.readdirSync(srcAbs).filter((f) => f.endsWith(".json")).sort();
  console.log(`Generando ${files.length} temas completos → ${DIST_DIR}\n`);

  const keysSet = new Set(ALL_KEYS);

  for (const f of files) {
    const srcPath = path.join(srcAbs, f);
    const origText = fs.readFileSync(srcPath, "utf8");
    const data = JSON.parse(origText);
    const colors = data.colors || {};
    const resolver = new Resolver(colors);

    const merged = {};
    for (const k of Object.keys(colors)) merged[k] = colors[k];

    let added = 0;
    const missing = Object.keys(colors).length
      ? [...keysSet].filter((k) => !(k in colors))
      : [];

    for (const k of missing) {
      const rule = RULES[k];
      if (!rule) continue;
      const v = rule(resolver);
      if (v == null) continue;
      merged[k] = v;
      added++;
    }

    const outText = rebuild(origText, merged, data);
    const outPath = path.join(distAbs, f);

    if (!DRY_RUN) {
      fs.mkdirSync(distAbs, { recursive: true });
      fs.writeFileSync(outPath, outText, "utf8");
    }

    const missingAfter = [...keysSet].filter((k) => !(k in merged));
    const tag = missingAfter.length === 0 ? "OK" : `faltan ${missingAfter.length}`;
    console.log(
      `${f.padEnd(14)} ${String(colors ? Object.keys(colors).length : 0).padStart(4)} → ${String(Object.keys(merged).length).padStart(4)} keys (+${added})  [${tag}]${DRY_RUN ? "  (dry-run)" : ""}`
    );
  }
  if (DRY_RUN) {
    console.log("\n(dry-run: no se escribió nada)");
  } else {
    console.log(`\nListo. Resultados en: ${distAbs}`);
    console.log("Revisá los JSON antes de sustituir los temas originales.");
  }
}

main();
