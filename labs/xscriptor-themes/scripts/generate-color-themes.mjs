// ── Utilidades de color ──
function hexToRgb(h) {
  h = String(h).replace("#", "").trim();
  if (h.length === 3) h = h.split("").map((c) => c + c).join("");
  if (h.length === 6) return [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16), 255];
  if (h.length === 8) return [parseInt(h.slice(0, 2), 16), parseInt(h.slice(2, 4), 16), parseInt(h.slice(4, 6), 16), parseInt(h.slice(6, 8), 16)];
  return [255, 255, 255, 255];
}
function rgbToHex(r, g, b, a = 255) {
  const h = (x) => Math.max(0, Math.min(255, Math.round(x))).toString(16).padStart(2, "0").toUpperCase();
  return a < 255 ? `#${h(r)}${h(g)}${h(b)}${h(a)}` : `#${h(r)}${h(g)}${h(b)}`;
}
function alpha(hex, a) {
  const [r, g, b] = hexToRgb(hex);
  return rgbToHex(r, g, b, a);
}
function mix(h1, h2, t = 0.5) {
  const a = hexToRgb(h1), b = hexToRgb(h2);
  const lerp = (x, y) => Math.round(x + (y - x) * t);
  return rgbToHex(lerp(a[0], b[0]), lerp(a[1], b[1]), lerp(a[2], b[2]), lerp(a[3], b[3]));
}
function lighten(h, f = 0.15) {
  const [r, g, b] = hexToRgb(h);
  const l = (x) => Math.round(x + (255 - x) * f);
  return rgbToHex(l(r), l(g), l(b));
}
function darken(h, f = 0.15) {
  const [r, g, b] = hexToRgb(h);
  const d = (x) => Math.round(x * (1 - f));
  return rgbToHex(d(r), d(g), d(b));
}

